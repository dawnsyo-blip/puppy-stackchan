def set_expr(expr: str):
    url = f"{BASE}/face?expr={expr}"
    try:
        r = requests.get(url, timeout=TIMEOUT)
        r.raise_for_status()
        print(f"  → 已切换到 {expr}  ({r.json()})")
    except requests.exceptions.RequestException as e:
        print(f"  [错误] 请求失败: {e}")


def main():
    print()
    print("=" * 60)
    print("  表情逐个查看  —  按回车进入下一个表情")
    print("=" * 60)
    print(f"  目标: {BASE}")
    print()

    i = 0
    while i < len(STEPS):
        expr, note = STEPS[i]
        print(f"[{i + 1}/{len(STEPS)}] {expr}")
        print(f"  {note}")
        set_expr(expr)

        cmd = input("\n  回车=下一个  r=重发当前  q=退出 > ").strip().lower()
        print()

        if cmd == "q":
            break
        elif cmd == "r":
            continue  # 停在原地，重新发送同一个表情
        else:
            i += 1

    print("复位为 neutral...")
    set_expr("neutral")
    print("结束。")


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        print("\n\n中断，复位为 neutral...")
